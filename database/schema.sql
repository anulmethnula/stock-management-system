CREATE TABLE IF NOT EXISTS suppliers (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL, contact TEXT, phone TEXT
);
CREATE TABLE IF NOT EXISTS products (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL, emoji TEXT DEFAULT '📦', image TEXT,
  supplier_id INTEGER NOT NULL REFERENCES suppliers(id),
  unit TEXT DEFAULT 'pieces', cost REAL NOT NULL DEFAULT 0,
  stock INTEGER NOT NULL DEFAULT 0, reorder INTEGER NOT NULL DEFAULT 5
);
CREATE TABLE IF NOT EXISTS purchase_orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  code TEXT, supplier_id INTEGER NOT NULL REFERENCES suppliers(id),
  date TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Ordered'
);
CREATE TABLE IF NOT EXISTS po_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  po_id INTEGER NOT NULL REFERENCES purchase_orders(id),
  product_id INTEGER NOT NULL REFERENCES products(id),
  qty INTEGER NOT NULL, cost REAL NOT NULL, received INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS grns (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  code TEXT, po_id INTEGER NOT NULL REFERENCES purchase_orders(id),
  supplier_id INTEGER NOT NULL, date TEXT NOT NULL, received_by TEXT, note TEXT
);
CREATE TABLE IF NOT EXISTS grn_lines (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  grn_id INTEGER NOT NULL REFERENCES grns(id),
  product_id INTEGER NOT NULL REFERENCES products(id),
  qty INTEGER NOT NULL
);
